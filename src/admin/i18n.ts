export function createT(lang: Lang): TFunc {
  const dict = translations[lang] ?? translations.en
  return (key: string, params?: Record<string, string | number>) => {
    let text = dict[key] ?? translations.en[key] ?? key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replaceAll(`{${k}}`, String(v))
      }
    }
    return text
  }
}

export function getLang(c: Context): Lang {
  const cookie = getCookie(c, 'lang')
  if (cookie === 'uk' || cookie === 'en') return cookie
  // Default to uk since html lang="uk"
  return 'uk'
}

export async function i18nMiddleware(c: Context, next: Next): Promise<Response | void> {
  const lang = getLang(c)
  c.set('lang', lang)
  c.set('t', createT(lang))
  return next()
}
